# QCEW sector code for a NAICS 3/4-digit code (the parent it rolls up to)
naics_sector <- function(naics) {
  s <- substr(naics, 1, 2)
  case_when(s %in% c("31", "32", "33") ~ "31-33",
            s %in% c("44", "45")       ~ "44-45",
            s %in% c("48", "49")       ~ "48-49",
            TRUE                       ~ s)
}

